import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {deliveryContractInventory} from './delivery-api-contracts.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const rows=deliveryContractInventory(root);
function combine(codes){return codes.length===1?codes[0]:codes.reduce((a,b)=>a?'z.intersection('+a+','+b+')':b,'');}
const manual={
 'POST /api/companies/{companyId}/dsp7-seats/{id}/verify':'z.object({revision:z.number().int().positive()})',
 'POST /api/agents/{id}/dsp7-jira-dispatch/verify':'z.object({taskId:z.string().uuid()})',
 'POST /api/agents/{id}/dsp7-jira-intake/authorize':'z.object({taskId:z.string().uuid()})',
};
const preview=rows.find(r=>r.path==='/api/companies/{companyId}/delivery-intake/preview');
manual['POST /api/companies/{companyId}/delivery-intake/import']=preview.body[0]+'.extend({fingerprint:z.string().regex(/^[a-f0-9]{64}$/)})';
const lines=[];
for(const r of rows){
 if(r.errors.length)throw Error(r.path+': '+r.errors.join('; '));
 const key=r.method.toUpperCase()+' '+r.path;
 const agent=r.path.startsWith('/api/agents/')||r.path==='/api/issues/{id}/dsp7-reservation';
 const auth=r.path.includes('/personnel-federation')?'instance_admin':['/api/dsp7-quick-enroll','/api/dsp7-quick-enroll/inspect','/api/dsp7-seat-enroll'].includes(r.path)?'public':agent?'seat_agent':'board';
 let bodies=manual[key]?[manual[key]]:r.body;
 if(agent&&r.method!=='get')bodies=['shared.managedIdentitySchema',...bodies];
 // The handler owns semantic checks (leases, revisions, membership and source versions).
 const item={method:r.method,path:r.path,source:r.source,auth,statuses:r.statuses};
 const body=combine([...new Set(bodies)]),query=key==='GET /api/companies/{companyId}/management-follow-ups'?'z.object({issueIds:z.string().optional().describe("Comma-separated UUIDs; at most 100 nonempty identifiers. Omitted or empty returns an empty list.")})':combine(r.query);
 lines.push('  {...'+JSON.stringify(item)+','+(body?'body:'+body+',':'')+(query?'query:'+query+',':'')+'},');
}
const code='// Generated by scripts/generate-delivery-api-contracts.mjs; do not edit.\n// Runtime Zod validators supply structural input contracts. Semantic refinements remain enforced by handlers.\nimport {z} from "zod";\nimport * as shared from "@paperclipai/shared";\nexport const deliveryApiContracts: ReadonlyArray<{method:string;path:string;source:string;auth:"board"|"seat_agent"|"public"|"instance_admin";statuses:number[];body?:z.ZodTypeAny;query?:z.ZodTypeAny}> = [\n'+lines.join('\n')+'\n];\n';
const target=new URL('../server/src/routes/generated-delivery-api-contracts.ts',import.meta.url);
if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==code)throw Error('Stale delivery API contracts; run node scripts/generate-delivery-api-contracts.mjs');}
else writeFileSync(target,code);
console.log('Delivery API contracts: '+rows.length+' routes '+(process.argv.includes('--check')?'verified':'generated'));
